-- Настройки сайта: вход (ключ auth) и колонки отчёта (ключ pnl).
--
-- Строки в уже существующей settings (000002), а не константы в Go: значения
-- меняют без пересборки и перезапуска. Обычные значения лежат здесь; если
-- строки нет или поле пустое/меньше 1, код берёт свои значения по умолчанию и
-- пишет предупреждение в лог — настройка не должна ронять вход и отчёт.
--
-- Сид, а не правка данных: ON CONFLICT DO NOTHING не затирает значение,
-- которое уже поправили руками, сколько раз ни накатывай. Это такое же
-- исключение из правила «только DDL», как сид в 000002.
--
-- auth:
--   session_ttl_days      скользящий срок сессии, дней: каждый запрос продлевает
--                         её на столько от последнего обращения
--   login_max_failures    неудачных входов подряд с одной пары «логин + адрес»,
--                         после которых вход запирается
--   login_window_minutes  окно подсчёта неудач и срок запрета, минут
--   min_password_length   минимальная длина пароля при заведении и смене
-- pnl:
--   default_months        сколько месяцев показывать, когда колонки не выбраны
--   max_columns           потолок колонок одного отчёта
INSERT INTO settings (key, value, description) VALUES (
    'auth',
    '{"session_ttl_days": 90, "login_max_failures": 5, "login_window_minutes": 15, "min_password_length": 10}',
    'Сайт: срок сессии (дни), лимит неудачных входов и окно (минуты), минимальная длина пароля'
), (
    'pnl',
    '{"default_months": 6, "max_columns": 12}',
    'ОПиУ на сайте: месяцев по умолчанию и потолок колонок'
) ON CONFLICT (key) DO NOTHING;
