-- Схема телеграм-бота: кто пускается к данным и чем настраиваются отчёты.
--
-- Обе таблицы живут отдельно от данных среза: они не версионируются, парсер их
-- не трогает, prunedb до них не добирается. Поэтому и миграция отдельная — откат
-- бота не должен задевать data/snapshots.

-- users — белый список доступа к финансовым данным.
--
-- Список в .env не годится: доступ выдают и отзывают чаще, чем перевыкладывают
-- сервис, а рестарт ради нового сотрудника — плохой обмен. Администратор из
-- TELEGRAM_ADMIN_ID пускается всегда и в таблице не обязан быть: иначе сразу
-- после миграции в боте не осталось бы ни одного пользователя, способного
-- выдать доступ остальным.
CREATE TABLE IF NOT EXISTS users (
    telegram_id BIGINT PRIMARY KEY,
    -- username хранится для чтения глазами: id в базе ни о чём не говорит.
    -- Не UNIQUE и не NOT NULL — в Telegram имя необязательно и меняется.
    username    TEXT,
    role        TEXT NOT NULL DEFAULT 'viewer',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- settings — настройки отчётов, редактируемые без пересборки.
--
-- Тип JSON, а не JSONB, намеренно: значение правится человеком (сейчас руками,
-- позже визуальным редактором), а JSONB нормализует текст — теряет отступы и
-- переставляет ключи, так что каждое сохранение меняло бы файл целиком.
-- Операторы и индексы JSONB здесь не нужны: настроек десяток, они читаются
-- целиком по первичному ключу.
CREATE TABLE IF NOT EXISTS settings (
    key         TEXT PRIMARY KEY,
    value       JSON NOT NULL,
    description TEXT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Единственное отступление от правила «миграции содержат только DDL» (CLAUDE.md).
-- Правило запрещает TRUNCATE/UPDATE/DELETE, то есть порчу данных; вставка
-- с ON CONFLICT DO NOTHING ничего не портит и никогда не затирает уже
-- отредактированное значение, сколько бы раз её ни накатили.
--
-- Дефолт нужен именно здесь, а не константой в Go: два источника правды у одного
-- списка расходятся молча, а пустая таблица настроек проявилась бы задвоенными
-- итогами в отчёте, а не ошибкой.
--
-- Исключаемые статьи — внутреннее движение денег, а не доход и не расход:
-- в сводке они дают вторую половину той же суммы и ломают итоги.
INSERT INTO settings (key, value, description) VALUES (
    'closed_reports',
    '{"excluded_items": ["пополнение", "перевод", "пополнение на оператора", "движение денег"]}',
    'Отчёт /closed_reports: статьи, исключаемые из сводки'
) ON CONFLICT (key) DO NOTHING;
