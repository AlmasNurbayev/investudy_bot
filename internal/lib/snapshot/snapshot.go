// Package snapshot решает, какая версия среза считается рабочей.
//
// Правило вынесено из репозитория, чтобы оно было одно на всех читателей:
// вью data_current прибита к новейшему срезу по taken_at безусловно, а
// «новейший непустой» — вопрос политики, а не SQL, и веб-отчёт должен отвечать
// на него так же, как бот, а не заводить своё определение.
package snapshot

import (
	"errors"

	"investudy_bot/internal/model"
)

// ErrNoSnapshot — читать нечего: ни одной непустой версии нет.
//
// Отдельная ошибка, а не пустой результат: «данные ещё не загружены» и «за
// период нет проводок» — разные новости, и пользователю их путать нельзя.
var ErrNoSnapshot = errors.New("нет ни одного непустого среза")

// Usable — срез пригоден для отчёта: заливка дописана и строки в нём есть.
//
// RowCount проставляет FinishSnapshot в той же транзакции, что и заливку,
// поэтому у любого закоммиченного среза он не NULL; Valid проверяется на
// случай ручной правки в базе. Сверять его с реальным count(*) незачем:
// prunedb уносит строки вместе с версией через ON DELETE CASCADE, так что
// полупустых срезов не бывает.
func Usable(s model.Snapshot) bool {
	return s.RowCount.Valid && s.RowCount.Int64 > 0
}

// Latest выбирает рабочую версию из списка, отсортированного по taken_at DESC.
//
// Пустой срез пропускается, а не показывается: неудачный прогон парсера не
// должен превращать отчёт в пустую таблицу — предыдущие данные лучше никаких.
// Что показана не самая свежая версия, читатель узнает из шапки отчёта.
func Latest(snapshots []model.Snapshot) (model.Snapshot, error) {
	for _, s := range snapshots {
		if Usable(s) {
			return s, nil
		}
	}

	return model.Snapshot{}, ErrNoSnapshot
}
